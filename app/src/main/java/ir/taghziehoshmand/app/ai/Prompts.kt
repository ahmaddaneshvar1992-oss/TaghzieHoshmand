    const val MEMORY_EXTRACT = """
از گفتگوی زیر بین کاربر و مشاور تغذیه، فقط «نکات ماندگار و کلیدی درباره کاربر» را استخراج کن؛
مثل: بیماری‌ها، آلرژی‌ها، غذاهای مورد علاقه یا منفور، محدودیت رژیمی یا مذهبی، سلیقه‌ها، شرایط زندگی.
خروجی: فقط یک فهرست کوتاه فارسی، هر مورد یک خط با پیشوند «-»، حداکثر ۴ مورد جدید.
چیزهای موقتی (مثل «امروز کالری خورده») و موارد تکراری را ننویس. اگر نکته جدیدی نیست فقط بنویس: هیچ
گفتگو:
"""

    /** بخش حافظه بلندمدت برای system prompt */
    fun memorySection(memory: String): String? {
        val m = memory.trim()
        if (m.isEmpty()) return null
        return "نکات ماندگاری که درباره کاربر از گفتگوهای قبلی یاد گرفته‌ای (به این‌ها پایبند بمان و بر اساس آن‌ها پاسخ را شخصی کن):\n$m"
    }

    /** بخش حالت رمضان برای system prompt */
    fun ramadanSection(suhoor: String, iftar: String): String =
        "کاربر در حالت رمضان است؛ پنجره غذایی از افطار ($iftar) تا سحر ($suhoor) است. " +
            "پیشنهادهای زمانی وعده‌ها و آب را فقط داخل همین پنجره بده و برنامه را برای روزه‌داری تنظیم کن."

    /** پرامپت استخراج غذا از جمله صوتی (ثبت صوتی — نسخه ۱.۵) */
