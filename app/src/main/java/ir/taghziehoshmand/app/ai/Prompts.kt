از جمله فارسی زیر غذاها/نوشیدنی‌های خورده‌شده را استخراج کن و دقیقاً با این قالب جواب بده (بدون متن اضافه):

غذا ۱: [نام غذا] — [گرم تقریبی] گرم — [کالری عدد] کالری — پ:[عدد] ک:[عدد] چ:[عدد]
